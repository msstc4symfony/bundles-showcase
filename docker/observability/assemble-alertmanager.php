<?php

declare(strict_types=1);

// Builds alertmanager.yml from alertmanager.base.yml and the slo-bundle fragment slo-alertmanager-routes.yml: the
// fragment's "routes" go under the base's "route", its "inhibit_rules" become a top-level key. All three apps share
// application "showcase", so their fragments must be identical; the fragment is pasted once.
// Usage: php assemble-alertmanager.php [--check]   (--check: exit 1 when alertmanager.yml is stale, write nothing)
// Text-level on purpose: no YAML library outside the apps' vendors, and the generator's output layout is fixed.

const APPS = ['gateway', 'orders', 'billing'];
const BASE = __DIR__ . '/alertmanager.base.yml';
const TARGET = __DIR__ . '/alertmanager.yml';

function fail(string $message): never
{
    fwrite(STDERR, $message . "\n");
    exit(1);
}

function read(string $path): string
{
    $contents = @file_get_contents($path);
    if ($contents === false) {
        fail("$path is missing (run make slo-generate)");
    }

    return str_replace("\r\n", "\n", $contents);
}

/**
 * @return array<string, list<string>> top-level key => its lines (the key line included)
 */
function topLevelBlocks(string $yaml, string $path): array
{
    $blocks = [];
    $key = null;
    foreach (explode("\n", rtrim($yaml, "\n")) as $line) {
        if ($line === '' || str_starts_with($line, '#')) {
            continue;
        }
        if (preg_match('/^([A-Za-z_]+):/', $line, $match) === 1) {
            $key = $match[1];
            if (isset($blocks[$key])) {
                fail("$path: duplicate top-level key $key");
            }
        } elseif ($key === null || !str_starts_with($line, ' ')) {
            fail("$path: unexpected line \"$line\"");
        }
        $blocks[$key][] = $line;
    }

    return $blocks;
}

$fragments = [];
foreach (APPS as $app) {
    $fragments[$app] = read(dirname(__DIR__, 2) . "/apps/$app/infrastructure/observability/alertmanager/slo-alertmanager-routes.yml");
}
if (count(array_unique($fragments)) !== 1) {
    fail('The apps\' slo-alertmanager-routes.yml differ (' . implode(', ', APPS) . '); they share application "showcase" and must be identical');
}
$fragmentPath = 'apps/' . APPS[0] . '/infrastructure/observability/alertmanager/slo-alertmanager-routes.yml';
$fragment = topLevelBlocks($fragments[APPS[0]], $fragmentPath);
if (array_keys($fragment) !== ['inhibit_rules', 'routes']) {
    fail("$fragmentPath: expected top-level keys inhibit_rules and routes, got " . implode(', ', array_keys($fragment)));
}

$base = read(BASE);
$baseBlocks = topLevelBlocks($base, BASE);
if (!isset($baseBlocks['route']) || isset($baseBlocks['inhibit_rules'])) {
    fail(BASE . ': needs a route block and no inhibit_rules (they come from the fragment)');
}
foreach ($baseBlocks['route'] as $line) {
    if (preg_match('/^  routes:/', $line) === 1) {
        fail(BASE . ': route must not declare routes (they come from the fragment)');
    }
}

$output = [
    '# Generated by make slo-generate (docker/observability/assemble-alertmanager.php) from alertmanager.base.yml',
    '# and ' . $fragmentPath . '. Do not edit.',
];
foreach ($baseBlocks as $key => $lines) {
    array_push($output, ...$lines);
    if ($key === 'route') {
        array_push($output, ...array_map(static fn (string $line): string => '  ' . $line, $fragment['routes']));
    }
}
array_push($output, ...$fragment['inhibit_rules']);
$assembled = implode("\n", $output) . "\n";

if (in_array('--check', $argv, true)) {
    if (!is_file(TARGET) || read(TARGET) !== $assembled) {
        fail('docker/observability/alertmanager.yml is stale (run make slo-generate)');
    }
    exit(0);
}

file_put_contents(TARGET, $assembled);
